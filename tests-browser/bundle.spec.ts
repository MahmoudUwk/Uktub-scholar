/**
 * Bundle proof: the import graphs of the five tool entries compile with the
 * alias table, and every still-stubbed node:* module is reported with the
 * core files/exports that reach it (the file-system, download and engine
 * seams' work list; `remainingNodeImports()` in build.mjs computes it on demand, no file is written).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { TOOL_ENTRIES, remainingNodeImports, ALIAS_TABLE } from "./build.mjs";
import { tmpDir } from "./tmp.mjs";

function renderRemaining(): string {
  const { perModule } = remainingNodeImports();
  const lines = [
    "# Remaining node:* imports (browser work list)",
    "",
    "Generated by `pnpm test:browser` (bundle proof). Every `node:*` module",
    "below is still a call-time-throwing stub in the browser build; the core",
    "files and exports that reach it are the file-system, download and engine",
    "seams' work list. Aliased (implemented): " + Object.keys(ALIAS_TABLE).join(", ") + ".",
    "Whole third-party packages stubbed as a unit: tar (archive handling).",
    "",
  ];
  const mods = [...perModule.entries()].sort();
  for (const [mod, files] of [...perModule.entries()].sort()) {
    lines.push(`## ${mod}`, "");
    for (const [f, names] of [...files.entries()].sort()) {
      lines.push(`- ${f}: ${[...names].sort().join(", ")}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

test("tool graphs bundle with the alias table", { timeout: 240000 }, async () => {
  const root = path.resolve(import.meta.dirname, "..");
  const { default: esbuild } = await import("esbuild");
  const { collectNodeImports, nodeShimPlugin } = await import("./build.mjs");
  const { assetPlugin } = await import("./assets-plugin.mjs");
  const found = collectNodeImports(path.join(root, "src"));
  const outdir = tmpDir("diff-tools-www-");
  const entries = Object.fromEntries(TOOL_ENTRIES.map((e) => [path.basename(e, ".ts"), path.join(root, e)]));
  let failed = "";
  try {
    await esbuild.build({
      entryPoints: entries, outdir, bundle: true, platform: "browser",
      format: "esm", target: "es2024", loader: { ".wasm": "file" },
      plugins: [nodeShimPlugin(found), assetPlugin(root)], logLevel: "warning",
    });
  } catch (err) {
    failed = err instanceof Error ? err.message : String(err);
  }
  assert.equal(failed, "", `tool bundle failed:\n${failed}`);
  console.log(`  bundled: ${TOOL_ENTRIES.join(", ")}`);

  assert.ok(renderRemaining().length > 0, "the work list of still-stubbed modules renders");
  const mods = [...remainingNodeImports().perModule.keys()].sort();
  console.log(`  still stubbed: ${mods.join(", ")}`);
  assert.ok(mods.length > 0, "expected some still-stubbed modules");

  // Stub contract in Node (stubs need no DOM): import is clean, calls throw.
  const probeOut = path.join(outdir, "stub-probe.js");
  await esbuild.build({
    entryPoints: { "stub-probe": path.join(root, "tests-browser/stub-probe.ts") },
    outdir, bundle: true, platform: "browser", format: "esm", target: "es2024",
    loader: { ".wasm": "file" }, plugins: [nodeShimPlugin(found), assetPlugin(root)], logLevel: "warning",
  });
  const probe = await import(pathToFileURL(probeOut).href);
  // node:fs is aliased to the implemented shim (not a stub): without an open
  // project it fails closed with the shim's pre-open error, never with the
  // stub contract message.
  assert.throws(() => probe.probeFs(), /fs shim used before openProjectFiles/);
  assert.throws(() => probe.probeChild(), /not implemented in the browser build: node:child_process\.spawn/);
  assert.match(probe.probeSqliteAlias(), /ensureBooted/);
});
